// The user manual: one Markdown file per chapter in manual/<machine>/<version>/,
// listed in order by that folder's README.md. This script joins them into
// manual.md (the whole manual in one file, for reading or for an LLM) and
// writes llms.txt beside it.
//
//   node manual/manual.mjs build <dir> <kit>    write manual.md and llms.txt
//   node manual/manual.mjs check <dir> <kit>    fail if they are stale, if a
//                                               heading repeats, if a link or
//                                               image is broken, or if a page
//                                               or cell of the kit's describe
//                                               schemas is never named
//   node manual/manual.mjs missing <dir> <kit> [chapter.md...]
//                                               what those chapters (default
//                                               all) leave unnamed
//
// <dir> is e.g. manual/preenfm3/0.4, <kit> e.g. editor/kit/0.4 (its fixtures/
// are the firmware's `ed describe` answers).
import fs from "node:fs";
import path from "node:path";

const [cmd, dir, kit, ...only] = process.argv.slice(2);
if (!["build", "check", "missing"].includes(cmd) || !dir || !kit) {
  console.error("usage: manual.mjs build|check|missing <dir> <kit> [chapter.md...]");
  process.exit(2);
}

const read = (f) => fs.readFileSync(path.join(dir, f), "utf8");
const index = read("README.md");
// Chapters in the order README.md links them: [Title](NN-name.md)
const chapters = [...new Set([...index.matchAll(/\]\((\d\d-[a-z0-9-]+\.md)\)/g)].map((m) => m[1]))];
const files = fs.readdirSync(dir).filter((f) => /^\d\d-.*\.md$/.test(f));
const unlisted = files.filter((f) => !chapters.includes(f));
const absent = chapters.filter((f) => !fs.existsSync(path.join(dir, f)));
if (cmd !== "missing" && absent.length) {
  console.error(`README.md lists chapters that do not exist: ${absent.join(", ")}`);
  process.exit(1);
}
const text = Object.fromEntries(chapters.filter((f) => !absent.includes(f)).map((f) => [f, read(f)]));

// GitHub's heading anchors: lower case, punctuation dropped, spaces to hyphens.
const anchor = (h) =>
  h
    .trim()
    .toLowerCase()
    .replace(/[^\p{L}\p{N} _-]/gu, "")
    .replace(/ /g, "-");
const headings = (md) =>
  md
    .replace(/```[\s\S]*?```/g, "")
    .split("\n")
    .filter((l) => /^#{1,6} /.test(l))
    .map((l) => l.replace(/^#+ /, ""));

// ---- manual.md ------------------------------------------------------------
const title = (headings(index)[0] || "Chimera manual").trim();
const toc = (f) => headings(text[f])[0];
function joined() {
  const relink = (md) =>
    md
      // a link to another chapter's heading becomes a link inside manual.md
      .replace(/\]\((\d\d-[a-z0-9-]+\.md)#([^)]+)\)/g, "](#$2)")
      // a link to a whole chapter, to its title
      .replace(/\]\((\d\d-[a-z0-9-]+\.md)\)/g, (m, f) => (text[f] ? `](#${anchor(toc(f))})` : m));
  const intro = index.replace(/^# .*\n/, "").trim();
  const parts = [
    `# ${title}`,
    "",
    "<!-- Generated by `just manual` from the chapters beside this file. Edit those, not this. -->",
    "",
    relink(intro),
    "",
    ...chapters.map((f) => relink(text[f].trim()) + "\n"),
  ];
  return parts.join("\n").replace(/\n{3,}/g, "\n\n");
}
function llms() {
  const lines = [
    `# ${title}`,
    "",
    "> The complete user manual of Chimera, multi-engine firmware for the PreenFM3 synthesizer: what every page and control does, and why it was designed that way.",
    "",
    "The whole manual is one Markdown file: [manual.md](manual.md). Read it first; every heading is stable and every section names the screen's own labels.",
    "",
    "## Chapters",
    "",
    ...chapters.map((f) => `- [${toc(f)}](${f})`),
    "",
  ];
  return lines.join("\n");
}

// ---- coverage -------------------------------------------------------------
// Every page and cell the firmware describes, by its on-screen label.
// DRUM's PAD1_KIT, the MIXER's PART1_EQ and ORBIT's RING1_NOTES are one page
// per pad, Part or ring: the page is KIT, EQ, NOTES.
function schemaItems(file) {
  const pages = new Set();
  const cells = new Set();
  const options = new Set();
  for (const line of fs.readFileSync(file, "utf8").split("\n")) {
    let m;
    if ((m = line.match(/^page \d+ (\S+) of/))) pages.add(m[1].replace(/^(PAD|PART|RING)\d+_/, ""));
    else if ((m = line.match(/^(?:param \S+|route|act|source) "([^"]+)"/))) cells.add(m[1]);
    else if ((m = line.match(/^opt \S+ \d+ "([^"]+)"/))) options.add(m[1]);
  }
  return { pages, cells, options };
}
const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
// A label is named when it stands as its own token: not inside a longer word.
const named = (hay, label) =>
  new RegExp(`(?<![\\p{L}\\p{N}_])${esc(label)}(?![\\p{L}\\p{N}_])`, "u").test(hay);

function coverage(hay) {
  const fixtures = path.join(kit, "fixtures");
  const out = [];
  for (const f of fs.readdirSync(fixtures).filter((f) => f.endsWith("-schema.txt")).sort()) {
    const { pages, cells, options } = schemaItems(path.join(fixtures, f));
    const miss = (set) => [...set].filter((l) => !named(hay, l));
    out.push({
      schema: f.replace("-schema.txt", "").toUpperCase(),
      pages: [pages.size, miss(pages)],
      cells: [cells.size, miss(cells)],
      options: [options.size, miss(options)],
    });
  }
  return out;
}

// ---- links ----------------------------------------------------------------
function brokenLinks() {
  const bad = [];
  const anchors = Object.fromEntries(chapters.map((f) => [f, new Set(headings(text[f]).map(anchor))]));
  const all = new Set(Object.values(anchors).flatMap((s) => [...s]));
  for (const f of ["README.md", ...chapters]) {
    const md = f === "README.md" ? index : text[f];
    for (const [, target] of md.matchAll(/\]\(([^)\s]+)\)/g)) {
      if (/^(https?:|mailto:)/.test(target)) continue;
      const [file, hash] = target.split("#");
      if (file === "" && hash) {
        if (!(f === "README.md" ? all : anchors[f]).has(hash)) bad.push(`${f}: #${hash}`);
      } else if (/^\d\d-.*\.md$/.test(file)) {
        if (!text[file]) bad.push(`${f}: ${target} (no such chapter)`);
        else if (hash && !anchors[file].has(hash)) bad.push(`${f}: ${target} (no such heading)`);
      } else if (!fs.existsSync(path.join(dir, file))) bad.push(`${f}: ${target} (no such file)`);
    }
  }
  return bad;
}

// ---- commands -------------------------------------------------------------
if (cmd === "build") {
  fs.writeFileSync(path.join(dir, "manual.md"), joined());
  fs.writeFileSync(path.join(dir, "llms.txt"), llms());
  console.log(`manual: ${chapters.length} chapters into ${path.join(dir, "manual.md")}`);
} else if (cmd === "missing") {
  const pick = only.length ? only : Object.keys(text);
  const hay = pick.map((f) => read(f)).join("\n");
  for (const r of coverage(hay))
    for (const k of ["pages", "cells", "options"])
      if (r[k][1].length) console.log(`${r.schema} ${k} (${r[k][1].length}/${r[k][0]} unnamed): ${r[k][1].join(" | ")}`);
} else {
  const errors = [];
  if (unlisted.length) errors.push(`chapters README.md does not list: ${unlisted.join(", ")}`);
  const fresh = (f, want) => {
    const p = path.join(dir, f);
    if (!fs.existsSync(p) || fs.readFileSync(p, "utf8") !== want) errors.push(`${f} is stale: run \`just manual\``);
  };
  fresh("manual.md", joined());
  fresh("llms.txt", llms());
  const seen = new Map();
  for (const f of chapters)
    for (const h of headings(text[f])) {
      const a = anchor(h);
      if (seen.has(a)) errors.push(`heading "${h}" in ${f} repeats one in ${seen.get(a)}`);
      else seen.set(a, f);
    }
  errors.push(...brokenLinks().map((b) => `broken link ${b}`));
  const hay = chapters.map((f) => text[f]).join("\n");
  let total = 0;
  let hit = 0;
  for (const r of coverage(hay)) {
    const line = ["pages", "cells", "options"].map((k) => `${k} ${r[k][0] - r[k][1].length}/${r[k][0]}`);
    console.log(`${r.schema.padEnd(9)} ${line.join("  ")}`);
    for (const k of ["pages", "cells"]) {
      total += r[k][0];
      hit += r[k][0] - r[k][1].length;
      if (r[k][1].length) errors.push(`${r.schema} ${k} the manual never names: ${r[k][1].join(" | ")}`);
    }
  }
  console.log(`pages and cells named: ${hit}/${total}`);
  if (errors.length) {
    console.error(errors.join("\n"));
    process.exit(1);
  }
  console.log("manual: up to date");
}
