// Writes src/Sign.elm and public/favicon.svg: the Yellow Sign as one SVG path, traced pixel for
// pixel from the firmware's splash bitmap (`node scripts/sign.js <yellow_sign.rle>`, the file
// from the firmware's source: 192 x 192, runs of ground then ink, alternating).
// Rows' ink runs become rectangles; identical runs on consecutive rows merge.
const fs = require("fs");
const path = require("path");

const SIZE = 192;
if (!process.argv[2]) throw new Error("usage: node scripts/sign.js <yellow_sign.rle>");
const rle = fs.readFileSync(process.argv[2]);
const ink = new Uint8Array(SIZE * SIZE);
let at = 0;
rle.forEach((run, i) => {
  if (i % 2 === 1) ink.fill(1, at, at + run);
  at += run;
});
if (at !== SIZE * SIZE) throw new Error(`runs cover ${at}, not ${SIZE * SIZE}`);

const rects = []; // [x, y, w, h]
let open = new Map(); // "x,w" -> rect still growing
for (let y = 0; y < SIZE; y++) {
  const next = new Map();
  for (let x = 0; x < SIZE; ) {
    if (!ink[y * SIZE + x]) { x++; continue; }
    let w = 0;
    while (x + w < SIZE && ink[y * SIZE + x + w]) w++;
    const key = `${x},${w}`;
    const r = open.get(key) ?? (rects.push([x, y, w, 0]), rects[rects.length - 1]);
    r[3]++;
    next.set(key, r);
    x += w;
  }
  open = next;
}
const d = rects.map(([x, y, w, h]) => `M${x} ${y}h${w}v${h}h-${w}z`).join("");

fs.writeFileSync(
  path.join(__dirname, "..", "src", "Sign.elm"),
  `-- SPDX-License-Identifier: GPL-3.0-or-later


module Sign exposing (view)

{-| The Yellow Sign, Chimera's mark: the boot splash's bitmap, traced.
Generated by scripts/sign.js; don't edit.
-}

import Svg exposing (Svg)
import Svg.Attributes as Attr


view : Svg msg
view =
    Svg.svg [ Attr.viewBox "0 0 ${SIZE} ${SIZE}", Attr.class "sign" ]
        [ Svg.path [ Attr.fill "currentColor", Attr.d "${d}" ] [] ]
`
);
fs.writeFileSync(
  path.join(__dirname, "..", "public", "favicon.svg"),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${SIZE} ${SIZE}"><rect width="${SIZE}" height="${SIZE}" rx="12" fill="#f1e579"/><path fill="#0a0b0d" d="${d}"/></svg>\n`
);
console.log(`${rects.length} rects, ${d.length} bytes`);
