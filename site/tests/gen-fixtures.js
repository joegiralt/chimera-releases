// Writes tests/Generated/Fixtures.elm: every Markdown file at the root of
// this repository (the guides) and the recorded releases API response, as
// Elm strings, for the tests to parse.
const fs = require("fs");
const path = require("path");

const here = __dirname;
const root = path.join(here, "..", "..");
const elm = (s) =>
  '"' +
  s.replace(/[\\"\n\r\t]|[\x00-\x1f]/g, (c) =>
    ({ "\\": "\\\\", '"': '\\"', "\n": "\\n", "\r": "\\r", "\t": "\\t" })[c] ??
    `\\u{${c.charCodeAt(0).toString(16).padStart(4, "0")}}`
  ) +
  '"';

const docs = fs
  .readdirSync(root)
  .filter((f) => f.endsWith(".md"))
  .sort()
  .map((f) => `( ${elm(f)}, ${elm(fs.readFileSync(path.join(root, f), "utf8"))} )`);
const manualDir = path.join(root, "manual", "preenfm3", "0.4");
const manual = fs
  .readdirSync(manualDir)
  .filter((f) => f.endsWith(".md") && f !== "manual.md")
  .sort()
  .map((f) => `( ${elm(f)}, ${elm(fs.readFileSync(path.join(manualDir, f), "utf8"))} )`);
const json = fs.readFileSync(path.join(here, "fixtures", "releases.json"), "utf8");

fs.mkdirSync(path.join(here, "Generated"), { recursive: true });
fs.writeFileSync(
  path.join(here, "Generated", "Fixtures.elm"),
  `module Generated.Fixtures exposing (docs, images, manual, manualImages, releasesJson)

{-| Generated by tests/gen-fixtures.js; not checked in. -}


docs : List ( String, String )
docs =
    [ ${docs.join("\n    , ")}
    ]


images : List String
images =
    [ ${fs.readdirSync(path.join(root, "docs", "img")).sort().map(elm).join(", ")} ]


manual : List ( String, String )
manual =
    [ ${manual.join("\n    , ")}
    ]


manualImages : List String
manualImages =
    [ ${fs.readdirSync(path.join(manualDir, "img")).sort().map(elm).join(", ")} ]


releasesJson : String
releasesJson =
    ${elm(json)}
`
);
